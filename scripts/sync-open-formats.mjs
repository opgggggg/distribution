async function readOptional(destination) {
	try {
		return await readFile(destination, "utf8");
	} catch (error) {
		if (error.code === "ENOENT") return "";
		throw error;
	}
}

const stale = [];
async function update(relativePath, content) {
	const destination = path.join(repositoryRoot, relativePath);
	if ((await readOptional(destination)) === content) return;
	stale.push(relativePath);
	if (checkOnly) return;
	await mkdir(path.dirname(destination), { recursive: true });
	await writeFile(destination, content);
	console.log(`Updated ${relativePath}`);
}

for (const [relativePath, content] of wholeFiles) await update(relativePath, content);
for (const [relativePath, start, end, body] of markedFiles) {
	const current = await readFile(path.join(repositoryRoot, relativePath), "utf8");
	await update(relativePath, replaceBlocks(relativePath, current, start, end, body));
}

if (checkOnly && stale.length > 0) {
	console.error(
		`Open-format artefacts are out of date; run npm run profile:sync:\n${stale.map((file) => `  ${file}`).join("\n")}`,
	);
	process.exit(1);
}
