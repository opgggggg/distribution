/** Replaces every marked block; `start` and `end` are the full marker lines. */
function replaceBlocks(relativePath, current, start, end, body) {
	const source = `(${escapeRegExp(start)})[\\s\\S]*?(\\n[\\t ]*${escapeRegExp(end)})`;
	if (!new RegExp(source).test(current)) {
		throw new Error(`${relativePath}: ${start.trim()} markers are missing`);
	}
	return current.replace(
		new RegExp(source, "g"),
		(_, opening, closing) => `${opening}\n${body}${closing}`,
	);
}

function escapeRegExp(value) {
	return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

