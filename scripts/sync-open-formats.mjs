// Wrapped the way google-java-format wraps a call past 100 columns.
const javaPut = (extension, mimeType) => {
	const line = `    SAVE_MIME_TYPES.put(${javaString(extension)}, ${javaString(mimeType)});`;
	return line.length <= 100
		? line
		: `    SAVE_MIME_TYPES.put(\n        ${javaString(extension)}, ${javaString(mimeType)});`;
};
