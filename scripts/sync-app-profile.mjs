import { copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = fileURLToPath(new URL("../", import.meta.url));
const profileName =
	process.env.APP_PROFILE || (process.argv.includes("--android") ? "cubeoffice" : "default");

if (!/^[a-zA-Z0-9._-]+$/.test(profileName)) {
	throw new Error(`Invalid APP_PROFILE: ${profileName}`);
}

const profileDirectory = path.join(repositoryRoot, "profiles", profileName);
const profilePath = path.join(profileDirectory, "app.json");
const profile = JSON.parse(await readFile(profilePath, "utf8"));

for (const field of ["name", "packageName", "vendor", "versionName", "icon", "urlScheme"]) {
	if (typeof profile[field] !== "string" || profile[field].trim() === "") {
		throw new Error(`${profilePath}: ${field} must be a non-empty string`);
	}
}
if (!Number.isInteger(profile.versionCode) || profile.versionCode <= 0) {
	throw new Error(`${profilePath}: versionCode must be a positive integer`);
}
if (!/^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z0-9][A-Za-z0-9_]*){2,}$/.test(profile.packageName)) {
	throw new Error(`${profilePath}: packageName is not a valid HarmonyOS/Android package name`);
}
if (!/^[a-z][a-z0-9+.-]*$/.test(profile.urlScheme)) {
	throw new Error(`${profilePath}: urlScheme must be a lowercase URI scheme`);
}

const iconPath = path.resolve(profileDirectory, profile.icon);
if (path.extname(iconPath).toLowerCase() !== ".png") {
	throw new Error(`${profilePath}: icon must reference a PNG file`);
}
const iconStat = await stat(iconPath);
if (!iconStat.isFile()) {
	throw new Error(`${iconPath} is not a file`);
}

const generatedHeader = "// Generated by scripts/sync-app-profile.mjs. Do not edit directly.";
const json5String = (value) => JSON.stringify(value);

const harmonyApp = `${generatedHeader}
{
	app: {
		bundleName: ${json5String(profile.packageName)},
		vendor: ${json5String(profile.vendor)},
		versionCode: ${profile.versionCode},
		versionName: ${json5String(profile.versionName)},
		icon: "$media:app_icon",
		label: "$string:app_name",
	},
}
`;

const harmonyStrings = `${JSON.stringify(
	{
		string: [
			{ name: "app_name", value: profile.name },
			{ name: "module_desc", value: "Open, edit, and view Office documents" },
			{ name: "EntryAbility_desc", value: `${profile.name} workspace` },
			{ name: "EntryAbility_label", value: profile.name },
			{ name: "app_loading", value: `正在载入 ${profile.name}…` },
		],
	},
	null,
	"\t",
)}
`;

const webProfile = `${generatedHeader}
export const APP_PROFILE = ${JSON.stringify(
	{
		name: profile.name,
		packageName: profile.packageName,
		versionName: profile.versionName,
		urlScheme: profile.urlScheme,
		documentTemplates: profile.documentTemplates ?? null,
	},
	null,
	"\t",
)} as const;
`;

const generatedFiles = [
	["apps/harmony/AppScope/app.json5", harmonyApp],
	["apps/harmony/entry/src/main/resources/base/element/string.json", harmonyStrings],
	["apps/harmony/web/src/app-profile.generated.ts", webProfile],
];

for (const [relativePath, content] of generatedFiles) {
	const destination = path.join(repositoryRoot, relativePath);
	await mkdir(path.dirname(destination), { recursive: true });
	let current = "";
	try {
		current = await readFile(destination, "utf8");
	} catch (error) {
		if (error.code !== "ENOENT") throw error;
	}
	if (current !== content) {
		await writeFile(destination, content);
		console.log(`Updated ${relativePath}`);
	}
}

const buildProfilePath = path.join(repositoryRoot, "apps/harmony/build-profile.json5");
const buildProfile = await readFile(buildProfilePath, "utf8");
const profileBlock = `\t\t\t\t// app-profile:start
\t\t\t\tbundleName: ${json5String(profile.packageName)},
\t\t\t\tvendor: ${json5String(profile.vendor)},
\t\t\t\tversionCode: ${profile.versionCode},
\t\t\t\tversionName: ${json5String(profile.versionName)},
\t\t\t\ticon: "$media:app_icon",
\t\t\t\tlabel: "$string:app_name",
\t\t\t\t// app-profile:end`;
const nextBuildProfile = buildProfile.replace(
	/\t\t\t\t\/\/ app-profile:start[\s\S]*?\t\t\t\t\/\/ app-profile:end/,
	profileBlock,
);
if (nextBuildProfile === buildProfile && !buildProfile.includes(profileBlock)) {
	throw new Error(`${buildProfilePath}: app profile markers are missing`);
}
if (nextBuildProfile !== buildProfile) {
	await writeFile(buildProfilePath, nextBuildProfile);
	console.log("Updated apps/harmony/build-profile.json5");
}

const harmonyIcon = path.join(
	repositoryRoot,
	"apps/harmony/AppScope/resources/base/media/app_icon.png",
);
await mkdir(path.dirname(harmonyIcon), { recursive: true });
await copyFile(iconPath, harmonyIcon);

console.log(
	`Applied app profile '${profileName}' from ${path.relative(repositoryRoot, profilePath)}`,
);
