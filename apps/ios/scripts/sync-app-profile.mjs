import { spawnSync } from "node:child_process";
import { copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * The Xcode counterpart of `apps/android/app/build.gradle.kts`: Gradle reads
 * `profiles/<profile>/app.json` directly, and Xcode cannot, so the same fields are
 * written out as an `.xcconfig` that the generated project includes. `Info.plist`
 * then refers to the build settings instead of hardcoding any identity.
 *
 * `npm --prefix ../.. run profile:sync -- --ios` still runs first (see package.json)
 * and owns validation plus the shared Web profile module; this script only adds the
 * iOS-specific artefacts.
 */
const repositoryRoot = fileURLToPath(new URL("../../../", import.meta.url));
const appRoot = fileURLToPath(new URL("../", import.meta.url));
const profileName = process.env.APP_PROFILE || "cubeoffice";

if (!/^[a-zA-Z0-9._-]+$/.test(profileName)) {
	throw new Error(`Invalid APP_PROFILE: ${profileName}`);
}

const profileDirectory = path.join(repositoryRoot, "profiles", profileName);
const profilePath = path.join(profileDirectory, "app.json");
const profile = JSON.parse(await readFile(profilePath, "utf8"));

// A free Apple ID registers a real App ID on Apple's side the first time it signs a
// build, and identifiers are globally unique. Someone else may already hold the
// profile's identifier, so allow an override without editing the shared profile.
const bundleIdentifier = process.env.IOS_BUNDLE_ID || profile.packageName;
if (!/^[A-Za-z][A-Za-z0-9-]*(\.[A-Za-z0-9-]+)+$/.test(bundleIdentifier)) {
	throw new Error(`Invalid iOS bundle identifier: ${bundleIdentifier}`);
}
if (!Number.isInteger(profile.versionCode) || profile.versionCode <= 0) {
	throw new Error(`${profilePath}: versionCode must be a positive integer`);
}

const xcconfigPath = path.join(appRoot, "App/Config/Generated.xcconfig");
const xcconfig = `// Generated by apps/ios/scripts/sync-app-profile.mjs. Do not edit directly.
// Source: profiles/${profileName}/app.json

APP_DISPLAY_NAME = ${profile.name}
APP_URL_SCHEME = ${profile.urlScheme}
PRODUCT_BUNDLE_IDENTIFIER = ${bundleIdentifier}
MARKETING_VERSION = ${profile.versionName}
CURRENT_PROJECT_VERSION = ${profile.versionCode}
`;

await mkdir(path.dirname(xcconfigPath), { recursive: true });
let currentXcconfig = "";
try {
	currentXcconfig = await readFile(xcconfigPath, "utf8");
} catch (error) {
	if (error.code !== "ENOENT") throw error;
}
if (currentXcconfig !== xcconfig) {
	await writeFile(xcconfigPath, xcconfig);
	console.log("Updated App/Config/Generated.xcconfig");
}

const sourceIcon = path.resolve(profileDirectory, profile.icon);
if (!(await stat(sourceIcon)).isFile()) {
	throw new Error(`${sourceIcon} is not a file`);
}

// A single-size asset catalogue entry needs exactly 1024x1024; `profiles/default`
// ships a 512px mark, so normalise instead of failing the build on it. The startup
// splash draws the same artwork at 256px rather than decoding the icon at launch.
const assets = path.join(appRoot, "App/Resources/Assets.xcassets");
const generatedIcons = [
	[path.join(assets, "AppIcon.appiconset/app-icon-1024.png"), 1024],
	[path.join(assets, "AppMark.imageset/app-mark.png"), 256],
];
for (const [destination, size] of generatedIcons) {
	await mkdir(path.dirname(destination), { recursive: true });
	await copyFile(sourceIcon, destination);
	const resize = spawnSync("sips", ["-z", String(size), String(size), destination], {
		stdio: "pipe",
	});
	if (resize.status !== 0) {
		throw new Error(
			`sips could not normalise the app icon to ${size}x${size}: ${resize.stderr}`,
		);
	}
}

console.log(
	`Applied app profile '${profileName}' to the iOS project as ${bundleIdentifier} ${profile.versionName} (${profile.versionCode})`,
);
