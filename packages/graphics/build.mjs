import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const compiler = spawnSync("rustup", ["which", "--toolchain", "1.88.0", "rustc"], {
	encoding: "utf8",
});
if (compiler.status !== 0)
	throw new Error("Install Rust 1.88.0 and its wasm32-unknown-unknown target.");
const result = spawnSync(
	"cargo",
	[
		"build",
		"--locked",
		"--release",
		"--target",
		"wasm32-unknown-unknown",
		"-p",
		"cubeoffice-graphics-core",
		"--message-format=json-render-diagnostics",
	],
	{
		cwd: root,
		encoding: "utf8",
		stdio: ["inherit", "pipe", "inherit"],
		env: { ...process.env, RUSTC: compiler.stdout.trim() },
	},
);
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
const wasm = result.stdout
	.split("\n")
	.filter(Boolean)
	.map(JSON.parse)
	.find(
		(message) =>
			message.reason === "compiler-artifact" &&
			message.target.name === "cubeoffice_graphics_core",
	)
	?.filenames.find((name) => name.endsWith(".wasm"));
if (!wasm) throw new Error("Graphics WASM was not built.");
const bytes = readFileSync(wasm);
if (!WebAssembly.validate(bytes)) throw new Error("Graphics WASM is invalid.");
writeFileSync(
	new URL("./src/kernel.generated.ts", import.meta.url),
	`// Generated by the Rust build.\nexport const GRAPHICS_WASM = ${JSON.stringify(bytes.toString("base64"))};\n`,
);
